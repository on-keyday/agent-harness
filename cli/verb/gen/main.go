// Command gen writes cli/verb/actions_gen.go from the declaration.
//
// The Action struct and the code that fills it used to be two hand-written
// halves joined by a hand-written Build, and nothing made them agree. Three
// defects came out of that seam in one afternoon: `agent wait --timeout` lost
// its 5-minute default to an int-vs-Duration mismatch, `ls --filtered` had no
// field to land in, and `Bound.Str` returns "" for a name the declaration does
// not have, so a rename leaves the Build reading nothing in silence.
//
// Generating both halves from one source removes the seam rather than testing
// across it. What cannot be generated stays declared: cross-flag rules are
// attributes (Exclusive / Requires / OneOf / ExactlyOne / AtLeastOne), and the
// residue is a Validate func on Bound -- deliberately on Bound and not on the
// Action, so the declaration never mentions a generated type and therefore
// still compiles when this file's output is missing. That is what lets the
// generator run to fix its own absence.
//
// It reflects over the evaluated Verbs rather than parsing table.go, because
// fifteen verbs build their flag lists by calling a function (spawnFlags,
// agentCommonFlags, …) and three use append: an AST reader sees none of those
// flags.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"github.com/on-keyday/agent-harness/cli/verb"
)

// field is one struct field the generator will emit.
type field struct {
	name    string
	goType  string
	comment string
}

// action collects the fields every verb that names this type contributes.
type action struct {
	name   string
	fields map[string]field
	order  []string
	verbs  []string
}

func main() {
	// -o lets the staleness check generate into a temp dir instead of over the
	// committed file, so a failing check leaves the tree untouched.
	out := flag.String("o", "actions_gen.go", "output path")
	flag.Parse()

	actions := map[string]*action{}
	var names []string
	builds := 0

	for _, v := range verb.Verbs {
		if v.Action == "" {
			continue // still hand-built
		}
		a := actions[v.Action]
		if a == nil {
			a = &action{name: v.Action, fields: map[string]field{}}
			actions[v.Action] = a
			names = append(names, v.Action)
		}
		a.verbs = append(a.verbs, v.FlagSetName())

		for _, f := range v.Flags {
			if f.PresenceField != "" {
				a.add(field{name: f.PresenceField, goType: "bool",
					comment: "whether --" + f.Name + " was typed, which its zero value cannot say"})
			}
			if f.Field == "" {
				continue
			}
			a.add(field{name: f.Field, goType: goTypeOfFlag(f), comment: f.Help})
		}
		for _, ar := range v.Args {
			if ar.Field == "" {
				continue
			}
			a.add(field{name: ar.Field, goType: goTypeOfArg(ar)})
		}
		if v.PathspecField != "" {
			a.add(field{name: v.PathspecField, goType: "string",
				comment: "the pathspec after `--`, which filters within a repository"})
		}
		if v.Trailing != nil {
			if v.Trailing.Field != "" {
				a.add(field{name: v.Trailing.Field, goType: "string", comment: v.Trailing.Reason})
			}
			if v.Trailing.FieldArgs != "" {
				a.add(field{name: v.Trailing.FieldArgs, goType: "[]string", comment: v.Trailing.Reason})
			}
		}
		for _, name := range sortedKeys(v.Const) {
			a.add(field{name: name, goType: "string"})
		}
		for _, d := range v.Derived {
			a.add(field{name: d.Field, goType: d.Type,
				comment: "computed by " + d.From + " from the whole line"})
		}
		if v.Modes != nil {
			a.add(field{name: v.Modes.Field, goType: "string",
				comment: strings.Join(v.Modes.Names, " | ")})
		}
		for _, name := range sortedKeys(v.ExtraFields) {
			a.add(field{name: name, goType: v.ExtraFields[name],
				comment: "set by the surface after Build, not by the parse"})
		}
	}
	sort.Strings(names)

	var buf bytes.Buffer
	fmt.Fprintf(&buf, `// Code generated by cli/verb/gen. DO NOT EDIT.
//
// The struct fields and the assignments that fill them both come from the
// declaration in table.go, so the two cannot disagree. Adding an option means
// adding a Flag with a Field -- never editing this file, and never a matching
// edit in two places.

package verb

import (
	"flag"
	"fmt"
	"io"
	"strconv"
	"strings"
	"time"
%s)

`, protocolImport(actions))

	for _, n := range names {
		a := actions[n]
		sort.Strings(a.verbs)
		fmt.Fprintf(&buf, "// %s is built by: %s.\ntype %s struct {\n\tActionMarker\n", n, strings.Join(a.verbs, ", "), n)
		for _, fn := range a.order {
			f := a.fields[fn]
			if f.comment != "" {
				fmt.Fprintf(&buf, "\t// %s\n", firstLine(f.comment))
			}
			fmt.Fprintf(&buf, "\t%s %s\n", f.name, f.goType)
		}
		buf.WriteString("}\n\n")
	}

	// One build func per verb path, registered by path so the table needs no
	// reference to a generated name.
	buf.WriteString("// The builds the declaration implies, one per verb path, registered into\n" +
		"// generated.go's map at init. Registering rather than declaring is what lets\n" +
		"// the package compile when this file is absent -- which it must, because the\n" +
		"// generator imports it.\nfunc init() {\n\tregisterGenerated(map[string]func(Bound) (Action, error){\n")
	// One build per (verb, surface): a positional the declaration narrows away
	// shifts every index after it. `file push` names <task-id> <local-src>
	// <dst> on the CLI and <task-id> <dst> in a browser, so a single build
	// keyed by path alone would write the destination into LocalSrc there.
	for _, v := range verb.Verbs {
		if v.Action == "" {
			continue
		}
		for _, sf := range []struct {
			s    verb.Surface
			name string
		}{{verb.CLI, "cli"}, {verb.TUI, "tui"}, {verb.WebUI, "webui"}} {
			if !v.Surfaces.Has(sf.s) {
				continue
			}
			nv := v.For(sf.s)
			emitBuild(&buf, nv, v.FlagSetName()+"\x00"+sf.name, v.Action)
			builds++
		}
	}
	buf.WriteString("\t})\n}\n")

	emitNamesAndParsers(&buf)
	emitDispatch(&buf)

	src, err := format.Source(buf.Bytes())
	if err != nil {
		os.WriteFile(*out, buf.Bytes(), 0o644)
		fmt.Fprintln(os.Stderr, "gen: emitted unformatted:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	fmt.Printf("gen: %d action types, %d verbs, %d builds\n", len(names), countGenerated(), builds)
}

// emitNamesAndParsers writes the half a CALLER touches: a name constant and a
// typed parse function per verb, then one dispatch interface and one dispatch
// function per surface.
//
// Before this, every call site spelled the verb as a STRING, looked it up,
// narrowed it, built a FlagSet, parsed, built, and type-asserted -- seven
// steps the compiler could not check, repeated in seven hand-written helpers
// (parseOne, parseSession, parseSpawn, parseViaSpec, parseViaSpec2,
// parseViaPath, parseCatalog) that differ only in which type they assert to.
// The failures that shape allows are the ones this migration kept finding:
// `.For(surface)` forgotten in two places, `cancel` never reaching Lookup at
// all, three verbs dispatched that the table did not declare.
//
// The interface is the part that replaces a TEST with a compile error. Go has
// no exhaustive switch, but a type that does not implement every method does
// not build -- so "every declared verb is dispatched" stops being something
// cmd/harness-cli/usage_completeness_test.go has to check after the fact.
func emitNamesAndParsers(buf *bytes.Buffer) {
	fmt.Fprintf(buf, "\n// Verb names. The dispatch case labels and the help headings both take\n"+
		"// these, so a rename in the table reaches every caller as a build error\n"+
		"// rather than as a case nothing matches.\nconst (\n")
	for _, v := range verb.Verbs {
		fmt.Fprintf(buf, "\tCmd%s = %q\n", methodName(v), v.FlagSetName())
	}
	buf.WriteString(")\n")

	// The values the declaration FIXES on an action's discriminator field --
	// Sub, Kind. Every surface switches on one, and every one of them spelled
	// the values by hand: `case "stream-turn"`, `case "ls"`. A rename in the
	// table left those matching nothing, silently, because a string case
	// label that no value reaches is not an error in Go.
	//
	// One constant per (field, value), not per verb: several verbs share a
	// value (five different `ls`), and what a switch compares is the value.
	type constPair struct{ field, value string }
	seenConst := map[constPair]bool{}
	var constOrder []constPair
	for _, v := range verb.Verbs {
		for _, field := range sortedKeys(v.Const) {
			cp := constPair{field, v.Const[field]}
			if seenConst[cp] {
				continue
			}
			seenConst[cp] = true
			constOrder = append(constOrder, cp)
		}
	}
	sort.Slice(constOrder, func(i, j int) bool {
		if constOrder[i].field != constOrder[j].field {
			return constOrder[i].field < constOrder[j].field
		}
		return constOrder[i].value < constOrder[j].value
	})
	fmt.Fprintf(buf, "\n// Discriminator values, as the table fixes them. A switch over an\n"+
		"// action's Sub or Kind takes these, so a value renamed in the table is a\n"+
		"// build error at every surface instead of a case nothing reaches.\nconst (\n")
	for _, cp := range constOrder {
		fmt.Fprintf(buf, "\t%s = %q\n", verb.ConstName(cp.field, cp.value), cp.value)
	}
	buf.WriteString(")\n")

	buf.WriteString("\n// Typed parsers. One per verb, and the only entry a caller needs: the\n" +
		"// name lives here, the surface narrowing is not forgettable, and the\n" +
		"// result is already the right type -- so a call site has no string, no\n" +
		"// ok-check and no assertion to get wrong.\n//\n" +
		"// Named ParseCmdXxx rather than ParseXxx because ParseCaps and\n" +
		"// ParseScope in this package are the capability and scope GRAMMARS,\n" +
		"// which a verb of the same name would shadow.\n")
	for _, v := range verb.Verbs {
		if v.Action == "" {
			continue
		}
		// ParseCmd, not Parse: ParseCaps and ParseScope are already the
		// capability and scope GRAMMAR parsers in this package, and a verb
		// named caps would silently shadow one of them.
		// The WHOLE ladder any flag here declares (D7), not just its
		// surface-context tier: env (HARNESS_REPO_PATH), workspace config,
		// then the value the surface knows. Emitting only the last tier meant
		// a caller reaching a verb through this parser lost the first two,
		// silently -- `submit` without --repo stopped seeing
		// HARNESS_REPO_PATH, on the parser the whole CLI is moving onto.
		//
		// The two the SURFACE owns come from EnvLookup / WorkspaceLookup,
		// installed once per process rather than passed at each of the call
		// sites that used to forget them.
		var ctxApply string
		for _, f := range v.Flags {
			if len(f.Resolve) == 0 || f.Field == "" {
				continue
			}
			ctxApply += fmt.Sprintf("\tif r := sp.Resolve(b, %q, EnvLookup, WorkspaceLookup, ctx); r != \"\" {\n\t\ta.%s = r\n\t}\n", f.Name, f.Field)
		}
		fmt.Fprintf(buf, "func ParseCmd%s(sf Surface, args []string, ctx map[string]string) (%s, error) {\n"+
			"\tvar zero %s\n"+
			"\tsp, ok := Lookup(%s)\n"+
			"\tif !ok {\n\t\treturn zero, fmt.Errorf(%q)\n\t}\n"+
			"\tsp = sp.For(sf)\n"+
			"\tfs := sp.NewFlagSet(flag.ContinueOnError)\n"+
			"\tfs.SetOutput(io.Discard)\n"+
			"\tb, err := sp.Parse(fs, args)\n"+
			"\tif err != nil {\n\t\treturn zero, err\n\t}\n"+
			"\tact, err := sp.BuildFunc()(b)\n"+
			"\tif err != nil {\n\t\treturn zero, err\n\t}\n"+
			"\ta := act.(%s)\n%s"+
			"\treturn a, nil\n}\n\n",
			methodName(v), v.Action, v.Action, quotedPath(v),
			v.FlagSetName()+": not in the verb table", v.Action, ctxApply)
	}
}

// emitDispatch writes, per surface, an interface with one method per declared
// verb and the function that routes a command line into it.
//
// The interface is the point. Go has no exhaustive switch, so "every declared
// verb is dispatched" was a TEST -- and the test could only see what it was
// told to look at, which is how `cancel` shipped reading args[0] with no
// arity check while the TUI refused the same line, and how three verbs got
// dispatched that the table did not declare. A type that does not implement
// every method does not build.
//
// What it does NOT unify is the method BODIES. Design D3: the CLI writes
// stdout and an exit code, the TUI returns a tea.Cmd, the WebUI touches the
// DOM, and forcing one output model on the other two is the thing the
// declaration was never meant to do. This fixes WHICH verbs each surface
// answers, not what answering means there.

// canonical groups verbs that are the SAME operation under two spellings --
// `quit` / `exit`, `refresh` / `sync`. D16 refused a path-alias mechanism, so
// they are two declared paths that fix the same Action and the same Const; the
// dispatch has to see one method, or the second spelling gets an interface
// method no dispatcher ever calls and a handler body nobody runs.
//
// Returns the verbs that own a method, in declaration order, and a lookup from
// any verb to the method that answers it.
func canonical(verbs []verb.VerbSpec) ([]verb.VerbSpec, func(verb.VerbSpec) string) {
	key := func(v verb.VerbSpec) string {
		keys := make([]string, 0, len(v.Const))
		for k := range v.Const {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		k := v.Action
		for _, name := range keys {
			k += "\x00" + name + "=" + v.Const[name]
		}
		return k
	}
	owner := map[string]string{}
	var own []verb.VerbSpec
	for _, v := range verbs {
		if _, seen := owner[key(v)]; seen {
			continue
		}
		owner[key(v)] = methodName(v)
		own = append(own, v)
	}
	return own, func(v verb.VerbSpec) string { return owner[key(v)] }
}

func emitDispatch(buf *bytes.Buffer) {
	for _, sf := range []struct {
		s    verb.Surface
		name string
	}{{verb.CLI, "CLI"}, {verb.TUI, "TUI"}} {
		var verbs []verb.VerbSpec
		for _, v := range verb.Verbs {
			if v.Action != "" && v.Surfaces.Has(sf.s) {
				verbs = append(verbs, v)
			}
		}
		fmt.Fprintf(buf, "\n// %sDispatch is every verb the declaration gives the %s. A handler type\n"+
			"// that misses one does not compile, which is what makes the coverage a\n"+
			"// build property rather than a test.\n//\n"+
			"// Generic in the RESULT because the surfaces do not agree on one: the\n"+
			"// CLI returns an error, the TUI a tea.Cmd. This package sits below\n"+
			"// both and imports neither (D23), so the shape of an answer is the\n"+
			"// caller's to name.\ntype %sDispatch[R any] interface {\n",
			sf.name, sf.name, sf.name)
		owners, methodOf := canonical(verbs)
		for _, v := range owners {
			var also []string
			for _, o := range verbs {
				if methodOf(o) == methodOf(v) && o.FlagSetName() != v.FlagSetName() {
					also = append(also, o.FlagSetName())
				}
			}
			line := v.FlagSetName()
			if len(also) > 0 {
				line += " (also: " + strings.Join(also, ", ") + ")"
			}
			fmt.Fprintf(buf, "\t// %s\n\t%s(%s) R\n", line, methodOf(v), v.Action)
		}
		buf.WriteString("}\n")

		fmt.Fprintf(buf, "\n// Dispatch%s parses one command line and hands it to the matching method.\n"+
			"// The switch is GENERATED, so no surface maintains a case list and none\n"+
			"// can fall through to a verb it forgot.\n//\n"+
			"// Returns handled=false for a name this surface does not declare, and a\n"+
			"// parse error before the handler runs -- the caller decides how each\n"+
			"// reads, which is the half D3 keeps per-surface.\n"+
			"func Dispatch%s[R any](h %sDispatch[R], cmd string, args []string, ctx map[string]string) (r R, handled bool, err error) {\n"+
			"\tswitch cmd {\n", sf.name, sf.name, sf.name)
		for _, v := range verbs {
			fmt.Fprintf(buf, "\tcase Cmd%s:\n\t\ta, perr := ParseCmd%s(%s, args, ctx)\n"+
				"\t\tif perr != nil {\n\t\t\treturn r, true, perr\n\t\t}\n\t\treturn h.%s(a), true, nil\n",
				methodName(v), methodName(v), sf.name, methodOf(v))
		}
		buf.WriteString("\t}\n\treturn r, false, nil\n}\n")

		// The tokens-in form. Every caller has a command LINE, not a
		// (path, args) pair, and splitting one into the other means knowing
		// that `session stream turn` is three words -- the knowledge the
		// hand-written surfaces each held their own copy of, and each got
		// wrong at a different arity.
		fmt.Fprintf(buf, "\n// Dispatch%sLine is Dispatch%s for a caller holding a whole command\n"+
			"// line. It finds the verb path itself, longest first, so nothing\n"+
			"// outside this file needs to know how many words a verb is.\n"+
			"//\n"+
			"// handled is false for a line this surface does not declare; the\n"+
			"// error is the PARSE error, returned with handled=true, because a\n"+
			"// misspelled flag on a known verb is not an unknown verb.\n"+
			"func Dispatch%sLine[R any](h %sDispatch[R], tokens []string, ctx map[string]string) (r R, handled bool, err error) {\n"+
			"\tfor n := MaxPathLen; n >= 1; n-- {\n\t\tif len(tokens) < n {\n\t\t\tcontinue\n\t\t}\n"+
			"\t\tif r, handled, err = Dispatch%s(h, strings.Join(tokens[:n], \" \"), tokens[n:], ctx); handled {\n"+
			"\t\t\treturn r, true, err\n\t\t}\n\t}\n\treturn r, false, nil\n}\n",
			sf.name, sf.name, sf.name, sf.name, sf.name)

		emitActionDispatch(buf, sf.name, verbs, methodOf)
		emitNameToAction(buf, sf.name, verbs)
	}
}

// emitNameToAction writes the name -> Action half, for a surface that PARSES
// separately from executing.
//
// The TUI does: ParseCommand turns a line into an Action that runAction later
// runs, because a keybinding produces the same Actions without a line. Its
// switch over declared verbs was the declaration's own table written out a
// second time, plus seventeen helper functions that differ only in which
// ParseCmdXxx they would now call.
func emitNameToAction(buf *bytes.Buffer, surface string, verbs []verb.VerbSpec) {
	fmt.Fprintf(buf, "\n// Parse%sCommand turns one tokenized command line into the Action the\n"+
		"// declaration says it is. It finds the verb path itself, longest first,\n"+
		"// so a caller never has to know that `session stream turn` is three words\n"+
		"// and `prune` is one.\n//\n"+
		"// handled is false for a name this surface does not declare, which is\n"+
		"// where a surface-local verb (the TUI's clear / quit / repo) takes over.\n"+
		"func Parse%sCommand(tokens []string, ctx map[string]string) (act Action, handled bool, err error) {\n"+
		"\tif len(tokens) == 0 {\n\t\treturn nil, false, nil\n\t}\n"+
		"\tfor n := MaxPathLen; n >= 1; n-- {\n\t\tif len(tokens) < n {\n\t\t\tcontinue\n\t\t}\n"+
		"\t\tswitch strings.Join(tokens[:n], \" \") {\n", surface, surface)
	for _, v := range verbs {
		fmt.Fprintf(buf, "\t\tcase Cmd%s:\n\t\t\ta, perr := ParseCmd%s(%s, tokens[n:], ctx)\n"+
			"\t\t\tif perr != nil {\n\t\t\t\treturn nil, true, perr\n\t\t\t}\n\t\t\treturn a, true, nil\n",
			methodName(v), methodName(v), surface)
	}
	buf.WriteString("\t\t}\n\t}\n\treturn nil, false, nil\n}\n")
}

// emitActionDispatch writes the ACTION-keyed half of a surface's dispatch.
//
// The TUI needs it because a command line is not its only source: a keybinding
// builds an Action directly and hands it to runAction, so a name-keyed
// dispatcher would cover one path and leave the other a hand-written type
// switch -- which is what it is today, unchecked, 37 cases long.
//
// Several verbs share an Action (SessionAction covers eleven), and they are
// told apart by the Const value the declaration fixes -- Sub, or Kind for the
// spawn family. That is the same discriminator the surfaces already switch on
// by hand; here it comes from the table.
func emitActionDispatch(buf *bytes.Buffer, surface string, verbs []verb.VerbSpec, methodOf func(verb.VerbSpec) string) {
	byAction := map[string][]verb.VerbSpec{}
	var order []string
	for _, v := range verbs {
		if _, seen := byAction[v.Action]; !seen {
			order = append(order, v.Action)
		}
		byAction[v.Action] = append(byAction[v.Action], v)
	}
	fmt.Fprintf(buf, "\n// Dispatch%sAction routes an ALREADY-PARSED action. The %s reaches its\n"+
		"// verbs from two places -- a command line and a keybinding -- and only\n"+
		"// this half covers both.\nfunc Dispatch%sAction[R any](h %sDispatch[R], act Action) (r R, handled bool) {\n"+
		"\tswitch a := act.(type) {\n", surface, surface, surface, surface)
	for _, name := range order {
		vs := byAction[name]
		fmt.Fprintf(buf, "\tcase %s:\n", name)
		if len(vs) == 1 && len(vs[0].Const) == 0 {
			fmt.Fprintf(buf, "\t\treturn h.%s(a), true\n", methodOf(vs[0]))
			continue
		}
		key := ""
		for _, v := range vs {
			for _, k := range sortedKeys(v.Const) {
				key = k
			}
		}
		if key == "" {
			fmt.Fprintf(buf, "\t\treturn h.%s(a), true\n", methodOf(vs[0]))
			continue
		}
		fmt.Fprintf(buf, "\t\tswitch a.%s {\n", key)
		var fallback string
		// Two paths may fix the SAME value -- `quit` and `exit`, `refresh`
		// and `sync`. They are one operation with two spellings (D16 refused
		// a path-alias mechanism, so they are two declared paths instead),
		// and the action dispatcher sees one case.
		emitted := map[string]bool{}
		for _, v := range vs {
			val, has := v.Const[key]
			if has && emitted[val] {
				continue
			}
			emitted[val] = true
			if !has {
				// The one verb of its type with no discriminator -- the CLI's
				// foreground `ssh-gateway` against its start/stop/status
				// siblings. It is the default rather than a case.
				fallback = methodOf(v)
				continue
			}
			fmt.Fprintf(buf, "\t\tcase %q:\n\t\t\treturn h.%s(a), true\n", val, methodOf(v))
		}
		if fallback != "" {
			fmt.Fprintf(buf, "\t\tdefault:\n\t\t\treturn h.%s(a), true\n", fallback)
		}
		buf.WriteString("\t\t}\n")
	}
	buf.WriteString("\t}\n\t// A surface-local action (the TUI's clear / quit / grid), which the\n" +
		"\t// declaration does not describe.\n\treturn r, false\n}\n")
}

// methodName turns a verb path into a Go identifier: `file push` -> FilePush,
// `caps set-parent` -> CapsSetParent.
func methodName(v verb.VerbSpec) string {
	var b strings.Builder
	for _, word := range v.Path {
		for _, part := range strings.Split(word, "-") {
			if part == "" {
				continue
			}
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return b.String()
}

// quotedPath renders a verb's path as Lookup arguments.
func quotedPath(v verb.VerbSpec) string {
	parts := make([]string, 0, len(v.Path))
	for _, p := range v.Path {
		parts = append(parts, fmt.Sprintf("%q", p))
	}
	return strings.Join(parts, ", ")
}

// emitBuild writes one build func for a verb already narrowed to a surface.
func emitBuild(buf *bytes.Buffer, v verb.VerbSpec, key, action string) {
	{
		fmt.Fprintf(buf, "\t\t%q: func(b Bound) (Action, error) {\n\t\t\ta := %s{}\n", key, action)
		for _, name := range sortedKeys(v.Const) {
			fmt.Fprintf(buf, "\t\ta.%s = %q\n", name, v.Const[name])
		}
		for _, f := range v.Flags {
			if f.PresenceField != "" {
				if f.PresenceAlso != "" {
					fmt.Fprintf(buf, "\t\ta.%s = b.Set[%q] || b.Set[%q]\n", f.PresenceField, f.Name, f.PresenceAlso)
				} else {
					fmt.Fprintf(buf, "\t\ta.%s = b.Set[%q]\n", f.PresenceField, f.Name)
				}
			}
			if f.Field == "" {
				continue
			}
			if f.Convert != "" {
				// Only on presence: the conversion produces a pointer or a
				// slice whose nil says the operator named nothing, and
				// converting the default would erase that.
				fmt.Fprintf(buf, "\t\tif b.Set[%q] {\n\t\t\tv, err := %s(%s)\n"+
					"\t\t\tif err != nil {\n\t\t\t\treturn nil, fmt.Errorf(%q, err)\n\t\t\t}\n"+
					"\t\t\ta.%s = v\n\t\t}\n",
					f.Name, f.Convert, rawReaderForFlag(f),
					v.FlagSetName()+": "+dashed(f.Name)+": %w", f.Field)
				continue
			}
			fmt.Fprintf(buf, "\t\ta.%s = %s\n", f.Field, readerForFlag(f))
		}
		for i, ar := range v.Args {
			if ar.Field == "" {
				continue
			}
			if ar.Variadic && ar.MaxCount != 1 && ar.Type == verb.ArgUint {
				// `exec kill 1 2 3` names ids, so the slice is numeric and the
				// parse happens once here rather than in each consumer.
				fmt.Fprintf(buf, "\t\tfor _, raw := range b.Args[%d:] {\n"+
					"\t\t\tn, err := strconv.ParseUint(raw, 10, 64)\n"+
					"\t\t\tif err != nil {\n\t\t\t\treturn nil, fmt.Errorf(%q, raw)\n\t\t\t}\n"+
					"\t\t\ta.%s = append(a.%s, n)\n\t\t}\n",
					i, v.FlagSetName()+": bad "+singular(ar.Name)+" %q", ar.Field, ar.Field)
			} else if ar.Variadic && ar.MaxCount == 1 && ar.Default != "" {
				// An optional single positional with a declared default.
				fmt.Fprintf(buf, "\t\ta.%s = %q\n\t\tif len(b.Args) > %d {\n\t\t\ta.%s = b.Args[%d]\n\t\t}\n",
					ar.Field, ar.Default, i, ar.Field, i)
			} else if ar.Variadic && ar.MaxCount != 1 {
				fmt.Fprintf(buf, "\t\tif len(b.Args) > %d {\n\t\t\ta.%s = b.Args[%d:]\n\t\t}\n", i, ar.Field, i)
			} else if ar.Type == verb.ArgUint {
				fmt.Fprintf(buf, "\t\tif len(b.Args) > %d {\n\t\t\tn, err := strconv.ParseUint(b.Args[%d], 10, 64)\n"+
					"\t\t\tif err != nil {\n\t\t\t\treturn nil, fmt.Errorf(%q, b.Args[%d])\n\t\t\t}\n"+
					"\t\t\ta.%s = n\n\t\t}\n",
					i, i, v.FlagSetName()+": bad "+singular(ar.Name)+" %q", i, ar.Field)
			} else {
				fmt.Fprintf(buf, "\t\tif len(b.Args) > %d {\n\t\t\ta.%s = b.Args[%d]\n\t\t}\n", i, ar.Field, i)
			}
		}
		for _, d := range v.Derived {
			fmt.Fprintf(buf, "\t\tif v, err := %s(b); err != nil {\n\t\t\treturn nil, err\n"+
				"\t\t} else {\n\t\t\ta.%s = v\n\t\t}\n", d.From, d.Field)
		}
		if v.Modes != nil {
			fmt.Fprintf(buf, "\t\ta.%s = %q\n", v.Modes.Field, v.Modes.Default)
			for _, m := range v.Modes.Names {
				if m == v.Modes.Default {
					continue
				}
				fmt.Fprintf(buf, "\t\tif b.Bool(%q) {\n\t\t\ta.%s = %q\n\t\t}\n", m, v.Modes.Field, m)
			}
		}
		if v.PathspecField != "" {
			// Only when present: git file lets the path arrive as a positional
			// OR after the separator, and both write the same field, so an
			// unconditional assignment would blank the positional form.
			fmt.Fprintf(buf, "\t\tif b.Pathspec != \"\" {\n\t\t\ta.%s = b.Pathspec\n\t\t}\n", v.PathspecField)
		}
		if v.Trailing != nil {
			if v.Trailing.Field != "" {
				if v.Trailing.IfFieldEmpty {
					fmt.Fprintf(buf, "\t\tif a.%s == \"\" {\n\t\t\ta.%s = b.Trail\n\t\t}\n",
						v.Trailing.Field, v.Trailing.Field)
				} else {
					fmt.Fprintf(buf, "\t\ta.%s = b.Trail\n", v.Trailing.Field)
				}
			}
			if v.Trailing.FieldArgs != "" {
				if v.Trailing.JoinWhen != "" {
					fmt.Fprintf(buf, "\t\tif b.Bool(%q) {\n\t\t\ta.%s = []string{b.Trail}\n\t\t} else {\n\t\t\ta.%s = b.TrailArgs\n\t\t}\n",
						v.Trailing.JoinWhen, v.Trailing.FieldArgs, v.Trailing.FieldArgs)
				} else {
					fmt.Fprintf(buf, "\t\ta.%s = b.TrailArgs\n", v.Trailing.FieldArgs)
				}
			}
		}
		buf.WriteString("\t\t\treturn a, nil\n\t\t},\n")
	}
}

// protocolImport adds the protocol import only when a generated field names
// it. An unconditional import breaks the build the day no action carries a
// capability.
func protocolImport(actions map[string]*action) string {
	for _, a := range actions {
		for _, f := range a.fields {
			if strings.Contains(f.goType, "protocol.") {
				return "\n\t\"github.com/on-keyday/agent-harness/runner/protocol\"\n"
			}
		}
	}
	return ""
}

func (a *action) add(f field) {
	if prev, seen := a.fields[f.name]; seen {
		if prev.goType != f.goType {
			fmt.Fprintf(os.Stderr, "gen: %s.%s declared as both %s and %s\n", a.name, f.name, prev.goType, f.goType)
			os.Exit(1)
		}
		return
	}
	a.fields[f.name] = f
	a.order = append(a.order, f.name)
}

// countGenerated counts VERBS carrying an Action -- not builds, of which
// there is one per (verb, surface) and therefore about twice as many.
func countGenerated() int {
	n := 0
	for _, v := range verb.Verbs {
		if v.Action != "" {
			n++
		}
	}
	return n
}

func goTypeOfFlag(f verb.Flag) string {
	if f.FieldType != "" {
		return f.FieldType
	}
	switch f.Type {
	case verb.FlagBool:
		return "bool"
	case verb.FlagString:
		if f.Custom != nil {
			return "[]string"
		}
		return "string"
	case verb.FlagUint:
		return "uint"
	case verb.FlagUint64:
		return "uint64"
	case verb.FlagDuration:
		return "time.Duration"
	}
	return "string"
}

func goTypeOfArg(a verb.Arg) string {
	// An ArgUint positional lands in a numeric field: `agent read 42` and
	// `forward tap 7` name an id, and every consumer that got a string had to
	// parse it again -- twice, differently, in the hand-written era.
	if a.Type == verb.ArgUint {
		if a.Variadic {
			return "[]uint64"
		}
		return "uint64"
	}
	// A variadic capped at one is an OPTIONAL single value, not a list --
	// `board subscribers [topic]` and `workspace show [name]` are one-or-none,
	// and giving them a []string would make every consumer index it.
	if a.Variadic && a.MaxCount != 1 {
		return "[]string"
	}
	return "string"
}

// rawReaderForFlag is the flag's value in its PARSED type, before any
// Convert -- what a converter takes as its argument.
func rawReaderForFlag(f verb.Flag) string {
	if f.Custom != nil {
		return fmt.Sprintf("stringsOf(b.Custom[%q])", f.Name)
	}
	switch f.Type {
	case verb.FlagBool:
		return fmt.Sprintf("b.Bool(%q)", f.Name)
	case verb.FlagUint:
		return fmt.Sprintf("uintOf(b.Flags[%q])", f.Name)
	case verb.FlagUint64:
		return fmt.Sprintf("uint64Of(b.Flags[%q])", f.Name)
	case verb.FlagDuration:
		return fmt.Sprintf("durationOf(b.Flags[%q])", f.Name)
	}
	return fmt.Sprintf("b.Str(%q)", f.Name)
}

// dashed spells a flag the way the operator types it.
func dashed(name string) string {
	if len(name) == 1 {
		return "-" + name
	}
	return "--" + name
}

func readerForFlag(f verb.Flag) string {
	if f.Custom != nil {
		return fmt.Sprintf("stringsOf(b.Custom[%q])", f.Name)
	}
	if f.FieldType != "" {
		// A cast the declaration asked for, written once here rather than at
		// every consumer that would otherwise do it by hand.
		switch f.Type {
		case verb.FlagUint:
			return fmt.Sprintf("%s(uintOf(b.Flags[%q]))", f.FieldType, f.Name)
		case verb.FlagUint64:
			return fmt.Sprintf("%s(uint64Of(b.Flags[%q]))", f.FieldType, f.Name)
		}
	}
	switch f.Type {
	case verb.FlagBool:
		return fmt.Sprintf("b.Bool(%q)", f.Name)
	case verb.FlagString:
		return fmt.Sprintf("b.Str(%q)", f.Name)
	case verb.FlagUint:
		return fmt.Sprintf("uintOf(b.Flags[%q])", f.Name)
	case verb.FlagUint64:
		return fmt.Sprintf("uint64Of(b.Flags[%q])", f.Name)
	case verb.FlagDuration:
		return fmt.Sprintf("durationOf(b.Flags[%q])", f.Name)
	}
	return fmt.Sprintf("b.Str(%q)", f.Name)
}

// sortedKeys yields a map's keys in a stable order so the output does not
// churn. It returns a SLICE: the first version sorted into another map and the
// caller ranged that, which discards the sort entirely. Harmless only while no
// verb declared two Const keys -- the day one did, the staleness test would
// have started failing on ~40% of runs, blaming table.go.
func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// singular renders a positional's name the way the hand-written errors did:
// `forward-id` reads as "forward id" in a sentence.
func singular(name string) string {
	return strings.ReplaceAll(name, "-", " ")
}

func firstLine(s string) string {
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		s = s[:i]
	}
	if len(s) > 100 {
		s = s[:100] + "…"
	}
	return s
}
