// Command gen writes cli/verb/actions_gen.go from the declaration.
//
// The Action struct and the code that fills it used to be two hand-written
// halves joined by a hand-written Build, and nothing made them agree. Three
// defects came out of that seam in one afternoon: `agent wait --timeout` lost
// its 5-minute default to an int-vs-Duration mismatch, `ls --filtered` had no
// field to land in, and `Bound.Str` returns "" for a name the declaration does
// not have, so a rename leaves the Build reading nothing in silence.
//
// Generating both halves from one source removes the seam rather than testing
// across it. What cannot be generated stays declared: cross-flag rules are
// attributes (Exclusive / Requires / OneOf / ExactlyOne / AtLeastOne), and the
// residue is a Validate func on Bound -- deliberately on Bound and not on the
// Action, so the declaration never mentions a generated type and therefore
// still compiles when this file's output is missing. That is what lets the
// generator run to fix its own absence.
//
// It reflects over the evaluated Verbs rather than parsing table.go, because
// fifteen verbs build their flag lists by calling a function (spawnFlags,
// agentCommonFlags, …) and three use append: an AST reader sees none of those
// flags.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"github.com/on-keyday/agent-harness/cli/verb"
)

// field is one struct field the generator will emit.
type field struct {
	name    string
	goType  string
	comment string
}

// action collects the fields every verb that names this type contributes.
type action struct {
	name   string
	fields map[string]field
	order  []string
	verbs  []string
}

func main() {
	// -o lets the staleness check generate into a temp dir instead of over the
	// committed file, so a failing check leaves the tree untouched.
	out := flag.String("o", "actions_gen.go", "output path")
	flag.Parse()

	actions := map[string]*action{}
	var names []string

	for _, v := range verb.Verbs {
		if v.Action == "" {
			continue // still hand-built
		}
		a := actions[v.Action]
		if a == nil {
			a = &action{name: v.Action, fields: map[string]field{}}
			actions[v.Action] = a
			names = append(names, v.Action)
		}
		a.verbs = append(a.verbs, v.FlagSetName())

		for _, f := range v.Flags {
			if f.PresenceField != "" {
				a.add(field{name: f.PresenceField, goType: "bool",
					comment: "whether --" + f.Name + " was typed, which its zero value cannot say"})
			}
			if f.Field == "" {
				continue
			}
			a.add(field{name: f.Field, goType: goTypeOfFlag(f), comment: f.Help})
		}
		for _, ar := range v.Args {
			if ar.Field == "" {
				continue
			}
			a.add(field{name: ar.Field, goType: goTypeOfArg(ar)})
		}
		if v.PathspecField != "" {
			a.add(field{name: v.PathspecField, goType: "string",
				comment: "the pathspec after `--`, which filters within a repository"})
		}
		if v.Trailing != nil {
			if v.Trailing.Field != "" {
				a.add(field{name: v.Trailing.Field, goType: "string", comment: v.Trailing.Reason})
			}
			if v.Trailing.FieldArgs != "" {
				a.add(field{name: v.Trailing.FieldArgs, goType: "[]string", comment: v.Trailing.Reason})
			}
		}
		for name := range v.Const {
			a.add(field{name: name, goType: "string"})
		}
		for _, d := range v.Derived {
			a.add(field{name: d.Field, goType: d.Type,
				comment: "computed by " + d.From + " from the whole line"})
		}
		if v.Modes != nil {
			a.add(field{name: v.Modes.Field, goType: "string",
				comment: strings.Join(v.Modes.Names, " | ")})
		}
		for name, typ := range v.ExtraFields {
			a.add(field{name: name, goType: typ,
				comment: "set by the surface after Build, not by the parse"})
		}
	}
	sort.Strings(names)

	var buf bytes.Buffer
	fmt.Fprintf(&buf, `// Code generated by cli/verb/gen. DO NOT EDIT.
//
// The struct fields and the assignments that fill them both come from the
// declaration in table.go, so the two cannot disagree. Adding an option means
// adding a Flag with a Field -- never editing this file, and never a matching
// edit in two places.

package verb

import (
	"fmt"
	"strconv"
	"time"
%s)

`, protocolImport(actions))

	for _, n := range names {
		a := actions[n]
		sort.Strings(a.verbs)
		fmt.Fprintf(&buf, "// %s is built by: %s.\ntype %s struct {\n\tActionMarker\n", n, strings.Join(a.verbs, ", "), n)
		for _, fn := range a.order {
			f := a.fields[fn]
			if f.comment != "" {
				fmt.Fprintf(&buf, "\t// %s\n", firstLine(f.comment))
			}
			fmt.Fprintf(&buf, "\t%s %s\n", f.name, f.goType)
		}
		buf.WriteString("}\n\n")
	}

	// One build func per verb path, registered by path so the table needs no
	// reference to a generated name.
	buf.WriteString("// The builds the declaration implies, one per verb path, registered into\n" +
		"// generated.go's map at init. Registering rather than declaring is what lets\n" +
		"// the package compile when this file is absent -- which it must, because the\n" +
		"// generator imports it.\nfunc init() {\n\tregisterGenerated(map[string]func(Bound) (Action, error){\n")
	// One build per (verb, surface): a positional the declaration narrows away
	// shifts every index after it. `file push` names <task-id> <local-src>
	// <dst> on the CLI and <task-id> <dst> in a browser, so a single build
	// keyed by path alone would write the destination into LocalSrc there.
	for _, v := range verb.Verbs {
		if v.Action == "" {
			continue
		}
		for _, sf := range []struct {
			s    verb.Surface
			name string
		}{{verb.CLI, "cli"}, {verb.TUI, "tui"}, {verb.WebUI, "webui"}} {
			if !v.Surfaces.Has(sf.s) {
				continue
			}
			nv := v.For(sf.s)
			emitBuild(&buf, nv, v.FlagSetName()+"\x00"+sf.name, v.Action)
		}
	}
	buf.WriteString("\t})\n}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		os.WriteFile(*out, buf.Bytes(), 0o644)
		fmt.Fprintln(os.Stderr, "gen: emitted unformatted:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	fmt.Printf("gen: %d action types, %d builds\n", len(names), countGenerated())
}

// emitBuild writes one build func for a verb already narrowed to a surface.
func emitBuild(buf *bytes.Buffer, v verb.VerbSpec, key, action string) {
	{
		fmt.Fprintf(buf, "\t\t%q: func(b Bound) (Action, error) {\n\t\t\ta := %s{}\n", key, action)
		for name, val := range sortedConst(v.Const) {
			_ = name
			fmt.Fprintf(buf, "\t\ta.%s = %q\n", val[0], val[1])
		}
		for _, f := range v.Flags {
			if f.PresenceField != "" {
				if f.PresenceAlso != "" {
					fmt.Fprintf(buf, "\t\ta.%s = b.Set[%q] || b.Set[%q]\n", f.PresenceField, f.Name, f.PresenceAlso)
				} else {
					fmt.Fprintf(buf, "\t\ta.%s = b.Set[%q]\n", f.PresenceField, f.Name)
				}
			}
			if f.Field == "" {
				continue
			}
			if f.Convert != "" {
				// Only on presence: the conversion produces a pointer or a
				// slice whose nil says the operator named nothing, and
				// converting the default would erase that.
				fmt.Fprintf(buf, "\t\tif b.Set[%q] {\n\t\t\tv, err := %s(%s)\n"+
					"\t\t\tif err != nil {\n\t\t\t\treturn nil, fmt.Errorf(%q, err)\n\t\t\t}\n"+
					"\t\t\ta.%s = v\n\t\t}\n",
					f.Name, f.Convert, rawReaderForFlag(f),
					v.FlagSetName()+": "+dashed(f.Name)+": %w", f.Field)
				continue
			}
			fmt.Fprintf(buf, "\t\ta.%s = %s\n", f.Field, readerForFlag(f))
		}
		for i, ar := range v.Args {
			if ar.Field == "" {
				continue
			}
			if ar.Variadic && ar.MaxCount != 1 && ar.Type == verb.ArgUint {
				// `exec kill 1 2 3` names ids, so the slice is numeric and the
				// parse happens once here rather than in each consumer.
				fmt.Fprintf(buf, "\t\tfor _, raw := range b.Args[%d:] {\n"+
					"\t\t\tn, err := strconv.ParseUint(raw, 10, 64)\n"+
					"\t\t\tif err != nil {\n\t\t\t\treturn nil, fmt.Errorf(%q, raw)\n\t\t\t}\n"+
					"\t\t\ta.%s = append(a.%s, n)\n\t\t}\n",
					i, v.FlagSetName()+": bad "+singular(ar.Name)+" %q", ar.Field, ar.Field)
			} else if ar.Variadic && ar.MaxCount != 1 {
				fmt.Fprintf(buf, "\t\tif len(b.Args) > %d {\n\t\t\ta.%s = b.Args[%d:]\n\t\t}\n", i, ar.Field, i)
			} else if ar.Type == verb.ArgUint {
				fmt.Fprintf(buf, "\t\tif len(b.Args) > %d {\n\t\t\tn, err := strconv.ParseUint(b.Args[%d], 10, 64)\n"+
					"\t\t\tif err != nil {\n\t\t\t\treturn nil, fmt.Errorf(%q, b.Args[%d])\n\t\t\t}\n"+
					"\t\t\ta.%s = n\n\t\t}\n",
					i, i, v.FlagSetName()+": bad "+singular(ar.Name)+" %q", i, ar.Field)
			} else {
				fmt.Fprintf(buf, "\t\tif len(b.Args) > %d {\n\t\t\ta.%s = b.Args[%d]\n\t\t}\n", i, ar.Field, i)
			}
		}
		for _, d := range v.Derived {
			fmt.Fprintf(buf, "\t\tif v, err := %s(b); err != nil {\n\t\t\treturn nil, err\n"+
				"\t\t} else {\n\t\t\ta.%s = v\n\t\t}\n", d.From, d.Field)
		}
		if v.Modes != nil {
			fmt.Fprintf(buf, "\t\ta.%s = %q\n", v.Modes.Field, v.Modes.Default)
			for _, m := range v.Modes.Names {
				if m == v.Modes.Default {
					continue
				}
				fmt.Fprintf(buf, "\t\tif b.Bool(%q) {\n\t\t\ta.%s = %q\n\t\t}\n", m, v.Modes.Field, m)
			}
		}
		if v.PathspecField != "" {
			// Only when present: git file lets the path arrive as a positional
			// OR after the separator, and both write the same field, so an
			// unconditional assignment would blank the positional form.
			fmt.Fprintf(buf, "\t\tif b.Pathspec != \"\" {\n\t\t\ta.%s = b.Pathspec\n\t\t}\n", v.PathspecField)
		}
		if v.Trailing != nil {
			if v.Trailing.Field != "" {
				if v.Trailing.IfFieldEmpty {
					fmt.Fprintf(buf, "\t\tif a.%s == \"\" {\n\t\t\ta.%s = b.Trail\n\t\t}\n",
						v.Trailing.Field, v.Trailing.Field)
				} else {
					fmt.Fprintf(buf, "\t\ta.%s = b.Trail\n", v.Trailing.Field)
				}
			}
			if v.Trailing.FieldArgs != "" {
				if v.Trailing.JoinWhen != "" {
					fmt.Fprintf(buf, "\t\tif b.Bool(%q) {\n\t\t\ta.%s = []string{b.Trail}\n\t\t} else {\n\t\t\ta.%s = b.TrailArgs\n\t\t}\n",
						v.Trailing.JoinWhen, v.Trailing.FieldArgs, v.Trailing.FieldArgs)
				} else {
					fmt.Fprintf(buf, "\t\ta.%s = b.TrailArgs\n", v.Trailing.FieldArgs)
				}
			}
		}
		buf.WriteString("\t\t\treturn a, nil\n\t\t},\n")
	}
}

// protocolImport adds the protocol import only when a generated field names
// it. An unconditional import breaks the build the day no action carries a
// capability.
func protocolImport(actions map[string]*action) string {
	for _, a := range actions {
		for _, f := range a.fields {
			if strings.Contains(f.goType, "protocol.") {
				return "\n\t\"github.com/on-keyday/agent-harness/runner/protocol\"\n"
			}
		}
	}
	return ""
}

func (a *action) add(f field) {
	if prev, seen := a.fields[f.name]; seen {
		if prev.goType != f.goType {
			fmt.Fprintf(os.Stderr, "gen: %s.%s declared as both %s and %s\n", a.name, f.name, prev.goType, f.goType)
			os.Exit(1)
		}
		return
	}
	a.fields[f.name] = f
	a.order = append(a.order, f.name)
}

func countGenerated() int {
	n := 0
	for _, v := range verb.Verbs {
		if v.Action != "" {
			n++
		}
	}
	return n
}

func goTypeOfFlag(f verb.Flag) string {
	if f.FieldType != "" {
		return f.FieldType
	}
	switch f.Type {
	case verb.FlagBool:
		return "bool"
	case verb.FlagString:
		if f.Custom != nil {
			return "[]string"
		}
		return "string"
	case verb.FlagUint:
		return "uint"
	case verb.FlagUint64:
		return "uint64"
	case verb.FlagDuration:
		return "time.Duration"
	}
	return "string"
}

func goTypeOfArg(a verb.Arg) string {
	// An ArgUint positional lands in a numeric field: `agent read 42` and
	// `forward tap 7` name an id, and every consumer that got a string had to
	// parse it again -- twice, differently, in the hand-written era.
	if a.Type == verb.ArgUint {
		if a.Variadic {
			return "[]uint64"
		}
		return "uint64"
	}
	// A variadic capped at one is an OPTIONAL single value, not a list --
	// `board subscribers [topic]` and `workspace show [name]` are one-or-none,
	// and giving them a []string would make every consumer index it.
	if a.Variadic && a.MaxCount != 1 {
		return "[]string"
	}
	return "string"
}

// rawReaderForFlag is the flag's value in its PARSED type, before any
// Convert -- what a converter takes as its argument.
func rawReaderForFlag(f verb.Flag) string {
	if f.Custom != nil {
		return fmt.Sprintf("stringsOf(b.Custom[%q])", f.Name)
	}
	switch f.Type {
	case verb.FlagBool:
		return fmt.Sprintf("b.Bool(%q)", f.Name)
	case verb.FlagUint:
		return fmt.Sprintf("uintOf(b.Flags[%q])", f.Name)
	case verb.FlagUint64:
		return fmt.Sprintf("uint64Of(b.Flags[%q])", f.Name)
	case verb.FlagDuration:
		return fmt.Sprintf("durationOf(b.Flags[%q])", f.Name)
	}
	return fmt.Sprintf("b.Str(%q)", f.Name)
}

// dashed spells a flag the way the operator types it.
func dashed(name string) string {
	if len(name) == 1 {
		return "-" + name
	}
	return "--" + name
}

func readerForFlag(f verb.Flag) string {
	if f.Custom != nil {
		return fmt.Sprintf("stringsOf(b.Custom[%q])", f.Name)
	}
	if f.FieldType != "" {
		// A cast the declaration asked for, written once here rather than at
		// every consumer that would otherwise do it by hand.
		switch f.Type {
		case verb.FlagUint:
			return fmt.Sprintf("%s(uintOf(b.Flags[%q]))", f.FieldType, f.Name)
		case verb.FlagUint64:
			return fmt.Sprintf("%s(uint64Of(b.Flags[%q]))", f.FieldType, f.Name)
		}
	}
	switch f.Type {
	case verb.FlagBool:
		return fmt.Sprintf("b.Bool(%q)", f.Name)
	case verb.FlagString:
		return fmt.Sprintf("b.Str(%q)", f.Name)
	case verb.FlagUint:
		return fmt.Sprintf("uintOf(b.Flags[%q])", f.Name)
	case verb.FlagUint64:
		return fmt.Sprintf("uint64Of(b.Flags[%q])", f.Name)
	case verb.FlagDuration:
		return fmt.Sprintf("durationOf(b.Flags[%q])", f.Name)
	}
	return fmt.Sprintf("b.Str(%q)", f.Name)
}

// sortedConst yields Const in a stable order so the output does not churn.
func sortedConst(m map[string]string) map[string][2]string {
	out := map[string][2]string{}
	var keys []string
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		out[k] = [2]string{k, m[k]}
	}
	return out
}

// singular renders a positional's name the way the hand-written errors did:
// `forward-id` reads as "forward id" in a sentence.
func singular(name string) string {
	return strings.ReplaceAll(name, "-", " ")
}

func firstLine(s string) string {
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		s = s[:i]
	}
	if len(s) > 100 {
		s = s[:100] + "…"
	}
	return s
}
