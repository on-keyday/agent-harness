"""Tests for the codebase-tour draw (runner/agentskills/codebase-tour/scripts/tour_draw.py)."""
import contextlib
import importlib.util
import io
import os
import subprocess
import sys
import tempfile
import textwrap
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPT = os.path.join(HERE, "..", "runner", "agentskills", "codebase-tour", "scripts", "tour_draw.py")
# Importing writes __pycache__ beside the script unless told not to, and
# //go:embed all:codebase-tour would then ship the .pyc to every task.
sys.dont_write_bytecode = True
spec = importlib.util.spec_from_file_location("tour_draw", SCRIPT)
tour_draw = importlib.util.module_from_spec(spec)
spec.loader.exec_module(tour_draw)

FENCE = "```"


def sh(cwd, *args):
    subprocess.run(args, cwd=cwd, check=True, capture_output=True)


class DrawTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.repo = os.path.join(self.tmp.name, "repo")
        self.tour = os.path.join(self.tmp.name, "tour")
        os.makedirs(os.path.join(self.repo, "a"))
        os.makedirs(os.path.join(self.repo, "b"))
        os.makedirs(self.tour)
        self.write("a/x.go", "package a\n\nfunc One() int {\n\treturn 1\n}\n")
        self.write("b/y.go", "package b\n\nfunc Two() int {\n\treturn 2\n}\n\nfunc Three() int {\n\treturn 3\n}\n")
        self.write("b/gen.go", "// Code generated by x. DO NOT EDIT.\npackage b\nvar Z = 1\n")
        self.write("docs/d.md", "a doc line\n")
        sh(self.repo, "git", "init", "-q")
        sh(self.repo, "git", "-c", "user.name=t", "-c", "user.email=t@t", "add", "-A")
        sh(self.repo, "git", "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qm", "c")
        self.settings("@generated\ndocs/\n")

    def tearDown(self):
        self.tmp.cleanup()

    def write(self, rel, text):
        path = os.path.join(self.repo, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(text)

    def settings(self, block):
        with open(os.path.join(self.tour, "settings.md"), "w") as f:
            f.write(f"# settings\n\n{FENCE}draw-exclude\n{block}{FENCE}\n")

    def page(self, name, body):
        with open(os.path.join(self.tour, name), "w") as f:
            f.write(textwrap.dedent(body))

    def run_draw(self, *extra):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            tour_draw.main(["--tour-dir", self.tour, "--repo", self.repo, *extra])
        return out.getvalue()

    def test_counts_exclude_generated_and_prefix(self):
        out = self.run_draw("--coverage")
        # a/x.go: package, func One, return 1 = 3; b/y.go: 5; gen.go and docs/ left out.
        self.assertIn("counted    8 lines in 2 directories", out)
        self.assertNotIn("docs", out.split("exclusions")[1].split("\n", 1)[1])

    def test_quoted_block_marks_lines_even_when_they_moved(self):
        # The page quotes a/x.go as if One were at line 10; content matching
        # still finds lines 3-4. The annotation and the elision mark nothing extra.
        self.page("001-2026-01-01.md", f"""\
            ## 1. x

            /abs/checkout/a/x.go:10

            {FENCE}go
            func One() int {{   // annotated
            \t...
            \treturn 1
            {FENCE}
            """)
        out = self.run_draw("--coverage")
        self.assertRegex(out, r"\n  a\s+2/3 ")

    def test_fully_shown_directory_is_never_drawn(self):
        self.page("001-2026-01-01.md", f"""\
            a/x.go:1

            {FENCE}go
            package a
            func One() int {{
            \treturn 1
            {FENCE}
            """)
        out = self.run_draw()
        self.assertIn("directory  b ", out)
        self.assertRegex(out, r"line       b/y\.go:\d+: ")

    def test_location_without_block_marks_its_range(self):
        self.page("001-2026-01-01.md", "See b/y.go:3-4 for Two.\n")
        out = self.run_draw("--coverage")
        self.assertRegex(out, r"\n  b\s+2/5 ")

    def test_walks_count_as_shown(self):
        os.makedirs(os.path.join(self.tour, "walks"))
        with open(os.path.join(self.tour, "walks", "001-2026-01-01-x.md"), "w") as f:
            f.write("a/x.go:1-5\n")
        out = self.run_draw("--coverage")
        self.assertRegex(out, r"\n  a\s+3/3 ")

    def test_same_commit_same_draw(self):
        self.assertEqual(self.run_draw(), self.run_draw())

    def test_missing_exclusion_block_refuses(self):
        with open(os.path.join(self.tour, "settings.md"), "w") as f:
            f.write("# settings\n")
        with self.assertRaises(SystemExit) as cm:
            self.run_draw()
        self.assertIn("draw-exclude", str(cm.exception.code))

    def test_everything_shown_draws_nothing(self):
        self.page("001-2026-01-01.md", "a/x.go:1-5\nb/y.go:1-9\n")
        out = self.run_draw()
        self.assertIn("nothing to draw", out)


if __name__ == "__main__":
    unittest.main()
